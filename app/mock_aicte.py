"""
mock_aicte.py -- a pretend regulator record book, used as a reference source.

PURPOSE   Stand-in for the regulator's own record of an institution (what intake it
          is approved for, under what legal name). The correlation engine compares
          the uploaded documents against it.
INPUTS    config/mock_aicte.json (generated by documents/make_synthetic.py)
OUTPUTS   SourceResponse from lookup(); references_for() turns it into the
          {shared_key: (source, value)} mapping that correlation.key_resolver.resolve takes
IMPORTS   contracts, correlation.normalizers
NOTE      MOCK DATA. Not connected to any real AICTE system.
"""
from __future__ import annotations

import hashlib
import json
import os
from typing import Optional

from app.contracts import SourceResponse
from app.correlation.normalizers import normalize_identifier

SOURCE = "mock_aicte"
DEFAULT_PATH = os.path.join(os.path.dirname(__file__), "..", "config", "mock_aicte.json")


def load_records(path: str = DEFAULT_PATH) -> dict[str, dict]:
    with open(path, encoding="utf-8") as fh:
        raw = json.load(fh)["institutions"]
    return {normalize_identifier(k): v for k, v in raw.items()}


class MockAicte:
    def __init__(self, records: Optional[dict[str, dict]] = None, outage: bool = False):
        self.records = records if records is not None else load_records()
        self.outage = outage

    def lookup(self, registration_number: str) -> SourceResponse:
        key = normalize_identifier(registration_number)
        if self.outage:
            return SourceResponse(id=f"sr_aicte_{key}", source=SOURCE, ok=False,
                                  error="mock AICTE did not respond (simulated outage)")
        rec = self.records.get(key)
        payload = {"found": True, **rec} if rec else {"found": False, "registration_number": registration_number}
        digest = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
        return SourceResponse(id=f"sr_aicte_{key}", source=SOURCE, ok=True, payload=payload, digest=digest)


def references_for(resp: SourceResponse) -> dict[str, tuple[str, str]]:
    """Shared-key readings from the regulator's record. Empty if it failed or has no record."""
    if not resp.ok or not resp.payload.get("found"):
        return {}
    # the label shows in the finding's reason: a dated snapshot says so, the mock stays "mock_aicte"
    label = resp.source + (f" {resp.payload['snapshot_date']}" if resp.payload.get("snapshot_date") else "")
    out = {}
    if "approved_intake" in resp.payload:
        out["approved_intake"] = (label, str(resp.payload["approved_intake"]))
    if "legal_name" in resp.payload:
        out["legal_name"] = (label, str(resp.payload["legal_name"]))
    return out
